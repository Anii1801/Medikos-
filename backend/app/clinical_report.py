"""Final clinical report: AI-generated summary -> red-flag suggestions -> clinician review.

The payload's ``display_order`` is part of the contract: the frontend renders the blocks in
exactly that order, and the red-flag block is always the one immediately after the summary.

Honest scope: the summary is a deterministic, extraction-first template over structured
answers and OCR text (no LLM is used). Red-flag wording is *provisional* until a local
clinician signs it off, and that status is shown next to every suggestion.
"""
from __future__ import annotations

import time
from typing import Any

from . import summary
from .clinical_nlp import ClinicalNLPService, get_service
from .redflag_engine import RedFlagEngine, RedFlagResult

RED_FLAG_LABEL = "Red-Flag Suggestions \u2014 Generated by AI"
SUMMARY_LABEL = "AI-Generated Clinical Summary"
NOTICE = ("AI-generated decision-support information. Not a confirmed diagnosis. "
          "Review by a qualified healthcare professional is required.")
NO_FLAG_MESSAGE = ("No red-flag rule was triggered by the available information. "
                   "This does not rule out an emergency.")
UNAVAILABLE_MESSAGE = ("Red-flag screening is unavailable or incomplete for this record. This is NOT a "
                       "\u201cno red flags\u201d result \u2014 obtain clinician review.")
URGENT_INSTRUCTION = ("Do not wait for this summary or for review: if the person may be unwell right now, "
                      "alert clinical staff / seek emergency care immediately.")
DISPLAY_ORDER = ["clinical_summary", "red_flag_suggestions", "clinician_review"]

REQUIRED_HISTORY = {
    "cc": "Chief complaint", "dur": "Onset / duration", "sev": "Severity", "progression": "Progression",
    "assoc": "Associated symptoms", "pmh": "Past medical / surgical history", "meds": "Current medicines",
    "allergy": "Allergies", "fam": "Family history",
}
_SOURCE_LABEL = {"patient": "Patient-reported statement", "document": "Document-derived (OCR text, unverified)",
                 "observation": "Recorded observation"}
_REVIEW_NOTE = {"provisional_pending_local_clinician_signoff":
                "Provisional wording \u2014 pending local clinician sign-off"}


def _empty(v: Any) -> bool:
    return v is None or v == "" or v == [] or v == {}


def _case(answers: dict[str, Any], docs: list[dict[str, Any]]) -> dict[str, Any]:
    clean = {k: v for k, v in answers.items() if not str(k).startswith("_") and k != "free"}
    reports = {}
    for i, d in enumerate(docs or []):
        if d.get("text"):
            reports[f"doc{d.get('id', i)}"] = d["text"]
    return {"symptoms": clean, "patient_description": answers.get("free") or "", "reports": reports}


def _finding_item(f) -> dict[str, Any]:
    return {
        "rule_id": f.rule.rule_id,
        "title": f.message,
        "urgency": f.urgency,
        "reason": f.reason,
        "evidence": [{
            "quote": e.quote, "source_id": e.source_id, "source_type": e.source_type,
            "source_label": _SOURCE_LABEL.get(e.source_type, e.source_type), "assertion": e.assertion,
            "temporal": e.temporal, "uncertainty_note": e.uncertainty_note,
        } for e in f.evidence_items],
        "missing_information": f.missing_information,
        "next_step": f.safe_next_step,
        "immediate_instruction": URGENT_INSTRUCTION if f.urgency == "EMERGENCY" else None,
        "rule_source": f"{f.rule.source} ({f.rule.source_version})",
        "rule_condition": f.rule.condition,
        "rule_review_status": f.rule.review_status,
        "rule_review_note": _REVIEW_NOTE.get(f.rule.review_status, f.rule.review_status),
        "human_review_required": f.human_review_required,
    }


def _red_flag_block(rf: RedFlagResult | None, error: str | None) -> dict[str, Any]:
    base = {"label": RED_FLAG_LABEL, "notice": NOTICE}
    if rf is None or rf.engine_status != "ok":
        return {**base, "screening_status": "unavailable", "urgency": None, "items": [],
                "message": UNAVAILABLE_MESSAGE, "missing_information": rf.missing_information if rf else [],
                "context_notes": [], "conflicts": [], "human_review_required": True,
                "error": error or (rf.classifier.error if rf else None)}
    return {**base, "screening_status": "complete",
            "urgency": rf.urgency if rf.findings else None,
            "items": [_finding_item(f) for f in rf.findings],
            "message": None if rf.findings else NO_FLAG_MESSAGE,
            "missing_information": rf.missing_information, "context_notes": rf.context_notes,
            "conflicts": rf.conflicts, "human_review_required": True, "error": None}


def build_clinical_report(user: dict[str, Any], answers: dict[str, Any], docs: list[dict[str, Any]],
                          *, engine: RedFlagEngine | None = None, nlp: ClinicalNLPService | None = None,
                          now: float | None = None) -> tuple[dict[str, Any], RedFlagResult | None]:
    """Return (report, red_flag_result). Never raises on screening failure."""
    nlp = nlp or get_service()
    engine = engine or RedFlagEngine(nlp=nlp)
    case = _case(answers, docs)
    rf: RedFlagResult | None = None
    err: str | None = None
    try:
        rf = engine.evaluate(case)
    except Exception as exc:  # defensive: evaluate() already fails safe, but never let this become "no flags"
        err = type(exc).__name__

    sections = summary.build_sections(user, {**answers}, docs or [])

    stated = []
    for f in (rf.facts if rf else []):
        if f.field in ("symptom", "condition") and f.source_type in ("patient", "document"):
            stated.append({"concept": f.concept.replace("_", " "), "assertion": f.assertion, "experiencer": f.experiencer,
                           "temporal": f.temporal.text if f.temporal else None, "quote": f.original_text,
                           "source_id": f.source_id, "source_label": _SOURCE_LABEL[f.source_type],
                           "verification_status": f.verification_status})
    missing = [{"field": k, "label": lbl, "status": "Not reported"} for k, lbl in REQUIRED_HISTORY.items() if _empty(answers.get(k))]
    missing.append({"field": "vitals_examination", "label": "Vital signs / examination", "status": "Not assessed"})
    uncertain = [s for s in stated if s["assertion"] == "uncertain"]
    conflicts = list(rf.conflicts) if rf else []
    conflicts += [{"type": "section_conflict", "concept": s["title"], "detail": s["text"],
                   "resolution": "unresolved - clinician to confirm"} for s in sections if s["title"] == "Conflicts requiring review"]
    ts = now if now is not None else time.time()
    report = {
        "display_order": DISPLAY_ORDER,
        "clinical_summary": {
            "label": SUMMARY_LABEL,
            "status": "DRAFT_UNREVIEWED",
            "status_text": "Draft \u2014 not reviewed by a clinician",
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(ts)),
            "generator": {"method": "deterministic template over structured answers + rule-based extraction",
                          "llm_used": False, "nlp": "ClinicalNLPService rule_v1 (untrained baseline, English only)"},
            "sections": sections,
            "patient_stated_findings": stated,
            "missing_or_uncertain": {"not_collected": missing, "uncertain": uncertain},
            "conflicts": conflicts,
            "provenance_note": "Patient-reported facts come from the interview; document-derived facts come from OCR "
                               "text and are unverified. No diagnosis or treatment is proposed.",
        },
        "red_flag_suggestions": _red_flag_block(rf, err),
        "clinician_review": {"status": "unreviewed", "approved": False, "reviewed_by": None, "reviewed_at": None,
                             "finding_reviews": {}, "actions": ["edit_summary", "confirm_or_reject_findings",
                                                                "review_red_flag_evidence", "approve", "export"]},
        "notice": NOTICE,
    }
    return report, rf
