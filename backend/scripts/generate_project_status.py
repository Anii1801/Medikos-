"""Generate docs/PROJECT_STATUS.md from an ACTUAL pytest run and the saved experiment artefacts.

    cd backend && PYTHONPATH=. python scripts/generate_project_status.py
One authoritative status document: counts and dates come from the run, not from prose.
"""
import json, re, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
run = subprocess.run([sys.executable, "-m", "pytest", "-q", "--ignore=tests/test_e2e_browser.py", "-p", "no:cacheprovider"],
                     cwd=ROOT / "backend", capture_output=True, text=True)
summary = [l for l in run.stdout.splitlines() if re.search(r"\d+ (passed|failed)", l)]
manifest = json.loads((ROOT / "backend/models/adaptive_ranker/v1/manifest.json").read_text())
reg = {
    "adaptive_ranker/v1": {"type": "trained (logistic regression, JSON weights)", "data": "synthetic", "created": manifest["created_utc"],
                           "weights_sha256": manifest["weights_sha256"], "default_in_app": False},
    "lab_extraction": {"type": "rules + Tesseract", "benchmark": "evaluation_results/lab_extraction/", "data": "synthetic"},
    "hindi_hinglish_nlp": {"type": "rules", "benchmark": "evaluation_results/hindi_nlp/", "data": "synthetic + hand-written"},
}
(ROOT / "evaluation_results" / "experiment_registry.json").write_text(json.dumps(reg, indent=2), encoding="utf-8")
doc = f"""# Project status (generated {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())})

Generated by `backend/scripts/generate_project_status.py`. This replaces hand-maintained status claims; if another document disagrees with this one, this one wins.

**Test run (browser e2e excluded):** `{summary[-1] if summary else 'no summary line; see below'}` (exit code {run.returncode})

| Area | Status |
|---|---|
| Trained model | `adaptive_ranker/v1` (checkpoint present, SHA-verified at load). Opt-in only; no evidence it beats the reviewed ontology policy (see `docs/EVALUATION_RESULTS.md`). |
| Neural checkpoints | None. Deliberately (templated synthetic data). |
| Lab extraction | Benchmarked on 1,238 labelled results; rendered-scan and scanned-PDF paths tested; synthetic data only. |
| Hindi/Hinglish | Rule layer measured on synthetic answers + hand-written cases; no audio. |
| Disease-prediction display | Absent from the doctor UI; API returns `likely_conditions: []` (tested). |
| Access control | `/api/eda/*` doctor-only; audit log; rate limiting; production-config enforcement. |
| Clinical governance | **All 8 red-flag rules still pending local clinician sign-off.** Deployment checker exits non-zero. |
| Browser end-to-end tests | Not run to completion in the authoring sandbox (fail identically on the original code); run on a machine with a working browser. |
| Real-patient / real-scan / real-audio validation | None. |

Experiment registry: `evaluation_results/experiment_registry.json`. Reproduce everything with `docs/MODEL_TRAINING.md`.
"""
(ROOT / "docs" / "PROJECT_STATUS.md").write_text(doc, encoding="utf-8")
print(doc.splitlines()[0]); print(summary[-1] if summary else run.stdout[-300:])
