"""Real-browser end-to-end test (Chromium via Playwright) of the clinician view.

Starts the actual server on a temp DB, submits synthetic records (software testing only),
then asserts on the *rendered DOM*: order of blocks, the exact label, failed/empty states,
approval flow, and HTML escaping. Skipped if Playwright/Chromium is unavailable.
"""
import os, socket, sqlite3, subprocess, sys, tempfile, time
import httpx
import pytest

pw = pytest.importorskip("playwright.sync_api")

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LABEL = "Red-Flag Suggestions \u2014 Generated by AI"
NONE_MSG = "No red-flag rule was triggered by the available information. This does not rule out an emergency."
NOTICE = ("AI-generated decision-support information. Not a confirmed diagnosis. "
          "Review by a qualified healthcare professional is required.")
EMERGENCY = {"cc": "Chest pain", "dur": "Today", "sev": "Severe", "assoc": ["Sweating"],
             "free": "Pressure in my chest. <img src=x onerror=window.__xss=1>"}
ROUTINE = {"cc": "Joint / back pain", "dur": "Months", "sev": "Mild", "progression": "Same", "assoc": ["None"]}


@pytest.fixture(scope="module")
def server():
    s = socket.socket(); s.bind(("127.0.0.1", 0)); port = s.getsockname()[1]; s.close()
    db = os.path.join(tempfile.mkdtemp(), "e2e.db")
    env = {**os.environ, "MEDIKIOSK_DB": db, "DOCTOR_USER": "doctor", "DOCTOR_PASS": "doctor123"}
    proc = subprocess.Popen([sys.executable, "-m", "uvicorn", "app.main:app", "--port", str(port), "--log-level", "warning"],
                            cwd=BACKEND, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    base = f"http://127.0.0.1:{port}"
    for _ in range(60):
        try:
            if httpx.get(base + "/api/health", timeout=1).status_code == 200:
                break
        except Exception:
            time.sleep(0.25)
    else:
        proc.kill(); pytest.fail("server did not start")
    yield base, db
    proc.terminate(); proc.wait(timeout=10)


def submit(base, answers, document=None):
    t = httpx.post(base + "/api/auth/guest?name=E2E").json()["token"]
    h = {"Authorization": f"Bearer {t}"}
    httpx.post(base + "/api/consent", json={"purpose": "history_capture", "granted": True}, headers=h)
    if document:
        filename, content = document
        response = httpx.post(base + "/api/documents",
                              files={"file": (filename, content, "text/plain")}, headers=h)
        assert response.status_code == 200, response.text
    return httpx.post(base + "/api/submit", json={"answers": answers}, headers=h).json()["record_id"]


@pytest.fixture(scope="module")
def records(server):
    base, db = server
    ids = {
        "emergency": submit(base, EMERGENCY, (
            "lab.txt", b"Laboratory Report 2025-03-12\nHaemoglobin 9.1 g/dL (13-17)"
        )),
        "routine": submit(base, ROUTINE),
        "legacy": submit(base, ROUTINE),
    }
    con = sqlite3.connect(db); con.execute("UPDATE records SET report=NULL WHERE id=?", (ids["legacy"],)); con.commit(); con.close()
    return ids


@pytest.fixture(scope="module")
def browser():
    with pw.sync_playwright() as p:
        try:
            b = p.chromium.launch()
        except Exception as e:
            pytest.skip(f"chromium unavailable: {e}")
        yield b
        b.close()


def open_record(browser, base, rid):
    page = browser.new_page()
    page.on("dialog", lambda d: d.dismiss())
    page.goto(base + "/doctor.html")
    page.fill("#u", "doctor"); page.fill("#p", "doctor123"); page.click("#go")
    page.click(f'[data-id="{rid}"]')
    page.wait_for_selector("#red-flag-suggestions")
    return page


def test_dom_order_label_notice_and_emergency_item(browser, server, records):
    base, _ = server
    page = open_record(browser, base, records["emergency"])
    blocks = page.eval_on_selector_all("[data-block]", "els => els.map(e => e.dataset.block)")
    assert blocks == ["clinical_summary", "red_flag_suggestions", "clinician_review"]
    # the red-flag section is the *immediate* next sibling of the summary card
    assert page.evaluate("document.getElementById('ai-summary').nextElementSibling.id") == "red-flag-suggestions"
    assert page.evaluate("document.getElementById('red-flag-suggestions').nextElementSibling.id") == "clinician-review"
    assert page.inner_text("#red-flag-suggestions h2") == LABEL
    assert page.inner_text("[data-testid=rf-notice]").strip() == NOTICE
    item = page.locator("#red-flag-suggestions .rf-item.rf-emergency").first
    text = item.inner_text()
    assert "EMERGENCY" in text                      # urgency stated in words, not colour alone
    assert "Why it triggered" in text and "Next step" in text and "Human review" in text and "Required" in text
    assert "Sweating" in text and "Patient-reported statement" in text and "symptoms.assoc[0]" in text
    assert "pending local clinician sign-off" in text
    assert item.get_attribute("role") == "alert"
    assert "draft" in page.inner_text("[data-testid=summary-status]").lower()
    page.close()


def test_interview_document_upload_and_management_flow(browser, server):
    base, _ = server
    token = httpx.post(base + "/api/auth/guest?name=PatientUI").json()["token"]
    headers = {"Authorization": f"Bearer {token}"}
    failed = httpx.post(base + "/api/documents",
                        files={"file": ("broken.pdf", b"not a PDF", "application/pdf")},
                        headers=headers)
    assert failed.status_code == 422
    document_id = failed.json()["id"]

    page = browser.new_page()
    page.set_default_timeout(5000)
    page.add_init_script(f"sessionStorage.setItem('mk_token', '{token}'); localStorage.setItem('mk_lang', 'en')")
    page.goto(base + "/dashboard.html")
    assert page.locator('a[href="reports.html"]').count() == 0
    assert page.get_by_role("link", name="Medical Reports").count() == 0
    page.goto(base + "/reports.html")
    assert page.url.endswith("/interview.html")
    page.goto(base + "/index.html")
    page.evaluate("docs()")
    page.get_by_role("heading", name="Upload medical reports").wait_for()
    assert page.locator("#up").inner_text() == "Upload"
    page.get_by_text("broken.pdf", exact=True).wait_for()
    page.locator("article.doc-item summary").first.click()
    page.select_option(f"#category-{document_id}", "prescription")
    page.locator(f'[data-document-save-category="{document_id}"]').click()
    page.get_by_text("Document category updated.").wait_for()

    page.locator("article.doc-item summary").first.click()
    page.locator(f'[data-document-replacement="{document_id}"]').set_input_files({
        "name": "replacement.txt",
        "mimeType": "text/plain",
        "buffer": b"Prescription\nTab Metformin 500 mg BD",
    })
    page.locator(f'[data-document-retry="{document_id}"]').click()
    page.get_by_text("replacement.txt", exact=True).wait_for()
    assert page.locator("article.doc-item .status-dot.ok").count() >= 1

    page.locator("#f").set_input_files({
        "name": "interview-upload.txt",
        "mimeType": "text/plain",
        "buffer": b"Laboratory Report\nHemoglobin 12.4 g/dL",
    })
    page.locator("#up").click()
    page.get_by_text("interview-upload.txt", exact=True).wait_for()

    page.on("dialog", lambda dialog: dialog.accept())
    page.locator("article.doc-item summary").first.click()
    page.locator(f'[data-document-delete="{document_id}"]').click()
    page.locator("article.doc-item summary").first.click()
    page.locator('[data-d]').click()
    page.get_by_text("No documents uploaded yet.").wait_for()
    page.close()


